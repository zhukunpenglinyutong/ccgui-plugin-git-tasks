export function Icon({ name, size = 14, className }) {
  return h("svg", {
    className,
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 2,
    strokeLinecap: "round",
    strokeLinejoin: "round",
    "aria-hidden": true,
    dangerouslySetInnerHTML: { __html: PATHS[name] || "" },
  });
}

export function Avatar({ name = "?" }) {
  return h(
    "span",
    { className: "ght-av", title: name },
    String(name)[0] ? String(name)[0].toUpperCase() : "?",
  );
}

export const repoColor = (index) => `var(--ght-repo-${(Number(index) % 8) + 1})`;

export const toneColor = (tone) =>
  tone === "neutral" ? "var(--color-text-tertiary, #a3a3a3)" : `var(--color-status-${tone}-text, #3b82f6)`;

export function RepoDot({ index, color }) {
  return h("i", { className: "ght-rd", style: { background: color || repoColor(index) } });
}

export function Chip({ tone, children, small }) {
  return h("span", { className: cx("ght-chip", `ght-tone-${tone || "neutral"}`, small && "ght-chip-sm") }, children);
}

export function Tag({ kind = "mute", children }) {
  return h("span", { className: `ght-tag ght-tag-${kind}` }, children);
}

export function useStore(store) {
  return React.useSyncExternalStore(store.subscribe, store.getSnapshot);
}

export function useNow(intervalMs = 60_000) {
  const [now, setNow] = React.useState(() => Date.now());
  React.useEffect(() => {
    const timer = setInterval(() => setNow(Date.now()), intervalMs);
    return () => clearInterval(timer);
  }, [intervalMs]);
  return now;
}

export function useEscape(handler, active = true) {
  React.useEffect(() => {
    if (!active) return undefined;
    const onKey = (event) => {
      if (event.key === "Escape") handler();
    };
    document.addEventListener("keydown", onKey);
    return () => document.removeEventListener("keydown", onKey);
  }, [handler, active]);
}
